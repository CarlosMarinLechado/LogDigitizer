"""Grid detection and internal penalty-mask creation for step 8.4D.4.

The source raster is never altered. Standard OpenCV HoughLines is used only
to identify repeated, nearly horizontal/vertical printed-grid families. Those
locations become a soft internal penalty mask for the minimum-cost tracker.

HoughLinesP is deliberately not used because this design does not require a
minimum segment length or maximum line-gap parameter.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import cos, isfinite, pi, sin

import cv2
import numpy as np


class GridDetectionError(ValueError):
    """Raised when a grid penalty mask cannot be constructed."""


@dataclass(frozen=True, slots=True)
class GridPenaltyResult:
    """Diagnostic output from one raster grid analysis."""

    penalty_mask: np.ndarray
    vertical_line_count: int
    horizontal_line_count: int

    @property
    def has_grid(self) -> bool:
        return (
            self.vertical_line_count > 0
            or self.horizontal_line_count > 0
        )


_ANGLE_TOLERANCE_DEG = 5.0
_MIN_FAMILY_LINES = 3
_HOUGH_VOTE_FRACTION = 0.32
_MIN_HOUGH_VOTES = 24
_CANNY_LOW = 50
_CANNY_HIGH = 150
_DEFAULT_LINE_WIDTH_PX = 3.0
_SPACING_REL_TOLERANCE = 0.22


def detect_grid_penalty_mask(
    image: np.ndarray,
    *,
    line_width_px: float | None = None,
) -> GridPenaltyResult:
    """Return a soft [0, 1] penalty mask for likely printed-grid lines.

    Candidate Hough responses must be nearly axis-aligned and participate in an
    approximately regularly spaced family. A single long straight curve segment
    is therefore not enough to become grid.
    """
    gray = _as_gray_uint8(image)
    height, width = gray.shape
    stroke_width = _validated_line_width(line_width_px)

    blurred = cv2.GaussianBlur(gray, (3, 3), 0)
    edges = cv2.Canny(
        blurred,
        _CANNY_LOW,
        _CANNY_HIGH,
        apertureSize=3,
        L2gradient=True,
    )

    vote_threshold = max(
        _MIN_HOUGH_VOTES,
        int(round(_HOUGH_VOTE_FRACTION * min(height, width))),
    )
    detected = cv2.HoughLines(
        edges,
        1.0,
        np.pi / 180.0,
        vote_threshold,
    )

    vertical: list[tuple[float, float, float]] = []
    horizontal: list[tuple[float, float, float]] = []

    if detected is not None:
        for entry in detected[:, 0, :]:
            rho = float(entry[0])
            theta = float(entry[1])
            orientation = _axis_orientation(theta)
            if orientation is None:
                continue

            position = _axis_position(
                rho,
                theta,
                orientation=orientation,
                width=width,
                height=height,
            )
            if not isfinite(position):
                continue

            if orientation == "vertical":
                if -stroke_width <= position <= width - 1 + stroke_width:
                    vertical.append((position, rho, theta))
            else:
                if -stroke_width <= position <= height - 1 + stroke_width:
                    horizontal.append((position, rho, theta))

    # Merge multiple Hough responses generated by both edges of one thick line,
    # but do not let nearby unrelated lines chain into the same cluster.
    dedupe_distance = max(3.0, 1.25 * stroke_width)
    vertical = _deduplicate_lines(
        vertical,
        min_distance_px=dedupe_distance,
    )
    horizontal = _deduplicate_lines(
        horizontal,
        min_distance_px=dedupe_distance,
    )

    # The regular-spacing filter is the main protection against treating a
    # long near-vertical/horizontal curve segment as printed grid.
    vertical = _select_regular_family(
        vertical,
        absolute_tolerance_px=max(2.0, stroke_width),
    )
    horizontal = _select_regular_family(
        horizontal,
        absolute_tolerance_px=max(2.0, stroke_width),
    )

    mask = np.zeros((height, width), dtype=np.float32)
    draw_thickness = max(
        1,
        int(round(max(2.0, stroke_width))),
    )

    for _position, rho, theta in (*vertical, *horizontal):
        _draw_hough_line(
            mask,
            rho=rho,
            theta=theta,
            thickness=draw_thickness,
        )

    if np.any(mask):
        # Soft edges make this a penalty rather than a hard forbidden region.
        sigma = max(0.8, 0.35 * stroke_width)
        mask = cv2.GaussianBlur(
            mask,
            (0, 0),
            sigmaX=sigma,
            sigmaY=sigma,
        )
        maximum = float(np.max(mask))
        if maximum > 0.0:
            mask = mask / maximum

    return GridPenaltyResult(
        penalty_mask=mask.astype(np.float32, copy=False),
        vertical_line_count=len(vertical),
        horizontal_line_count=len(horizontal),
    )


def _axis_orientation(theta: float) -> str | None:
    tolerance = np.deg2rad(_ANGLE_TOLERANCE_DEG)
    vertical_distance = min(
        abs(theta),
        abs(pi - theta),
    )
    horizontal_distance = abs(theta - 0.5 * pi)

    if vertical_distance <= tolerance:
        return "vertical"
    if horizontal_distance <= tolerance:
        return "horizontal"
    return None


def _axis_position(
    rho: float,
    theta: float,
    *,
    orientation: str,
    width: int,
    height: int,
) -> float:
    if orientation == "vertical":
        y = 0.5 * (height - 1)
        denominator = cos(theta)
        if abs(denominator) < 1e-9:
            return float("nan")
        return (rho - y * sin(theta)) / denominator

    x = 0.5 * (width - 1)
    denominator = sin(theta)
    if abs(denominator) < 1e-9:
        return float("nan")
    return (rho - x * cos(theta)) / denominator


def _deduplicate_lines(
    lines: list[tuple[float, float, float]],
    *,
    min_distance_px: float,
) -> list[tuple[float, float, float]]:
    """Collapse multiple Hough responses without single-linkage chaining."""
    if not lines:
        return []

    ordered = sorted(lines, key=lambda item: item[0])
    clusters: list[list[tuple[float, float, float]]] = [[ordered[0]]]

    for item in ordered[1:]:
        cluster_mean = float(
            np.mean([entry[0] for entry in clusters[-1]])
        )
        if abs(item[0] - cluster_mean) <= min_distance_px:
            clusters[-1].append(item)
        else:
            clusters.append([item])

    result: list[tuple[float, float, float]] = []
    for cluster in clusters:
        mean_position = float(
            np.mean([entry[0] for entry in cluster])
        )
        representative = min(
            cluster,
            key=lambda entry: abs(entry[0] - mean_position),
        )
        result.append(
            (mean_position, representative[1], representative[2])
        )
    return result


def _select_regular_family(
    lines: list[tuple[float, float, float]],
    *,
    absolute_tolerance_px: float,
) -> list[tuple[float, float, float]]:
    """Keep lines participating in the dominant repeated spacing pattern."""
    if len(lines) < _MIN_FAMILY_LINES:
        return []

    ordered = sorted(lines, key=lambda item: item[0])
    positions = np.asarray(
        [item[0] for item in ordered],
        dtype=float,
    )
    gaps = np.diff(positions)
    positive = gaps[
        gaps > max(1.0, 0.5 * absolute_tolerance_px)
    ]
    if positive.size < _MIN_FAMILY_LINES - 1:
        return []

    spacing = float(np.median(positive))
    tolerance = max(
        absolute_tolerance_px,
        _SPACING_REL_TOLERANCE * spacing,
    )

    keep = np.zeros(len(ordered), dtype=bool)
    for index, gap in enumerate(gaps):
        if abs(float(gap) - spacing) <= tolerance:
            keep[index] = True
            keep[index + 1] = True

    selected = [
        item
        for item, accepted in zip(ordered, keep)
        if accepted
    ]
    if len(selected) < _MIN_FAMILY_LINES:
        return []
    return selected


def _draw_hough_line(
    mask: np.ndarray,
    *,
    rho: float,
    theta: float,
    thickness: int,
) -> None:
    a = cos(theta)
    b = sin(theta)
    x0 = a * rho
    y0 = b * rho
    extent = 100000

    point1 = (
        int(round(x0 + extent * (-b))),
        int(round(y0 + extent * a)),
    )
    point2 = (
        int(round(x0 - extent * (-b))),
        int(round(y0 - extent * a)),
    )
    cv2.line(
        mask,
        point1,
        point2,
        color=1.0,
        thickness=thickness,
        lineType=cv2.LINE_AA,
    )


def _validated_line_width(
    line_width_px: float | None,
) -> float:
    if line_width_px is None:
        return _DEFAULT_LINE_WIDTH_PX
    try:
        value = float(line_width_px)
    except (TypeError, ValueError, OverflowError) as exc:
        raise GridDetectionError(
            "line_width_px must be a positive finite number."
        ) from exc

    if not isfinite(value) or value <= 0.0:
        raise GridDetectionError(
            "line_width_px must be a positive finite number."
        )
    return value


def _as_gray_uint8(image: np.ndarray) -> np.ndarray:
    array = np.asarray(image)
    if array.size == 0:
        raise GridDetectionError(
            "Grid-detection image cannot be empty."
        )

    if array.ndim == 2:
        gray = array.astype(np.float64, copy=False)
    elif array.ndim == 3 and array.shape[2] in (1, 3, 4):
        if array.shape[2] == 1:
            gray = array[..., 0].astype(np.float64, copy=False)
        else:
            rgb = array[..., :3].astype(np.float64, copy=False)
            gray = (
                0.2126 * rgb[..., 0]
                + 0.7152 * rgb[..., 1]
                + 0.0722 * rgb[..., 2]
            )
    else:
        raise GridDetectionError(
            "Grid-detection image must be grayscale or RGB(A)."
        )

    if not np.isfinite(gray).all():
        raise GridDetectionError(
            "Grid-detection image cannot contain NaN or infinite values."
        )

    low = float(np.percentile(gray, 1.0))
    high = float(np.percentile(gray, 99.0))
    if high <= low + 1e-12:
        return np.zeros(gray.shape, dtype=np.uint8)

    normalized = (gray - low) / (high - low)
    normalized = np.clip(normalized, 0.0, 1.0)
    return np.round(255.0 * normalized).astype(np.uint8)
